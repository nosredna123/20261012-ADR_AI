"""Validate the frozen catalog and optionally compare public Git blob hashes."""

import hashlib
import importlib.util
import json
from pathlib import Path
import sys
from urllib.request import urlopen

PROJECT = Path(__file__).resolve().parents[2]
CATALOG = PROJECT / "docs/20261012.0933-InitialArtifacts/adr4ai_app/catalogs/patterns"
LOADER = CATALOG.parents[1] / "experiments/pattern_selection/prepare_data.py"
FIELDS = ("id", "name", "motivation", "solution", "consequences")
UPSTREAM_REVISION = "9ff3e611583b7d0f71032c62f9a9812ce93e2fd0"
UPSTREAM_URL = (
    "https://api.github.com/repos/SWE4AI/ai-patterns/git/trees/"
    + UPSTREAM_REVISION + "?recursive=1"
)
AUDIT = PROJECT / "processing/outputs/catalog-summary-audit.json"
MACROS = PROJECT / "latex-code/data/catalog-values.tex"
PROVENANCE = PROJECT / "processing/outputs/catalog-upstream-verification.json"


def summarize_catalog() -> dict:
    spec = importlib.util.spec_from_file_location("catalog_original_loader", LOADER)
    if spec is None or spec.loader is None:
        raise ValueError(f"Cannot load original validator: {LOADER}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    patterns = module.load_patterns(CATALOG)
    expected_ids = [f"{number:03d}" for number in range(1, 71)]
    if [pattern["id"] for pattern in patterns] != expected_ids:
        raise ValueError("Expected pattern IDs 001 through 070 in filename order")
    empty = {field: [] for field in FIELDS}
    records = []
    for pattern, pattern_id in zip(patterns, expected_ids):
        path = CATALOG / f"P{pattern_id}.json"
        data = path.read_bytes()
        for field in FIELDS:
            if field not in pattern or not isinstance(pattern[field], str):
                raise ValueError(f"{path.name}: missing or non-string {field}")
            if pattern[field] == "":
                empty[field].append(pattern_id)
        if not pattern["name"].strip():
            raise ValueError(f"{path.name}: empty pattern name")
        resources = pattern.get("resources")
        if not isinstance(resources, list) or any(
            not isinstance(item, str) for item in resources
        ):
            raise ValueError(f"{path.name}: invalid resource identifiers")
        records.append({
            "file": path.name,
            "id": pattern_id,
            "sha256": hashlib.sha256(data).hexdigest(),
            "git_blob_sha1": hashlib.sha1(
                f"blob {len(data)}\0".encode("ascii") + data
            ).hexdigest(),
            "resources": resources,
        })
    return {
        "task": "1.3",
        "source_directory": CATALOG.relative_to(PROJECT).as_posix(),
        "validator": LOADER.relative_to(PROJECT).as_posix(),
        "validator_sha256": hashlib.sha256(LOADER.read_bytes()).hexdigest(),
        "pattern_count": len(patterns),
        "model_input_fields": list(FIELDS),
        "empty_fields": empty,
        "records": records,
    }


def render_outputs(audit: dict) -> dict[Path, str]:
    empty_count = sum(len(ids) for ids in audit["empty_fields"].values())
    return {
        AUDIT: json.dumps(audit, indent=2, sort_keys=True) + "\n",
        MACROS: (
            "% !TeX root = ../main.tex\n"
            "% Generated by processing/scripts/prepare_catalog_summary.py.\n"
            "% StudyPatternCount is owned by data/study-values.tex.\n"
            f"\\newcommand{{\\CatalogEmptyFieldCount}}{{{empty_count}}}\n"
        ),
    }


def verify_upstream(audit: dict) -> None:
    with urlopen(UPSTREAM_URL, timeout=30) as response:
        tree = json.load(response)
    if tree.get("truncated") is not False or not isinstance(tree.get("tree"), list):
        raise ValueError("Incomplete upstream Git tree")
    upstream = {item["path"]: item["sha"] for item in tree["tree"]
                if item.get("type") == "blob"}
    mismatches = []
    for record in audit["records"]:
        path = "ai-patterns/patterns/" + record["file"]
        if upstream.get(path) != record["git_blob_sha1"]:
            mismatches.append(record["file"])
    result = {
        "repository": "https://github.com/SWE4AI/ai-patterns",
        "revision": UPSTREAM_REVISION,
        "tree_url": UPSTREAM_URL,
        "comparison": "Git blob SHA-1 over exact file bytes",
        "local_audit_sha256": hashlib.sha256(
            render_outputs(audit)[AUDIT].encode("utf-8")
        ).hexdigest(),
        "compared_files": audit["pattern_count"],
        "matching_files": audit["pattern_count"] - len(mismatches),
        "mismatched_or_missing_files": mismatches,
    }
    PROVENANCE.parent.mkdir(parents=True, exist_ok=True)
    PROVENANCE.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n",
                          encoding="utf-8")
    print(f"Upstream exact-byte matches: {result['matching_files']}/"
          f"{result['compared_files']}")
    if mismatches:
        raise ValueError(f"Upstream provenance mismatch: {mismatches}")


def main() -> int:
    if sys.argv[1:] not in ([], ["--check"], ["--verify-upstream"]):
        raise ValueError("Usage: prepare_catalog_summary.py [--check|--verify-upstream]")
    audit = summarize_catalog()
    outputs = render_outputs(audit)
    if sys.argv[1:] == ["--check"]:
        for path, content in outputs.items():
            if path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Stale catalog artifact: {path}")
        print("PASS: catalog validation and generated artifacts match")
    elif sys.argv[1:] == ["--verify-upstream"]:
        verify_upstream(audit)
    else:
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(PROJECT)}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, ImportError) as error:
        print(f"Catalog verification failed: {error}", file=sys.stderr)
        sys.exit(1)
