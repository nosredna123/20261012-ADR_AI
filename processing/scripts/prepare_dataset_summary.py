"""Verify the original requirement sample and render Task 1.2 paper artifacts."""

import hashlib
import importlib.util
import json
from pathlib import Path
import sys

PROJECT = Path(__file__).resolve().parents[2]
LATEX = PROJECT / "latex-code"
SOURCE_ROOT = PROJECT / "docs/20261012.0933-InitialArtifacts"
SOURCE = SOURCE_ROOT / "adr4ai_app/data/user_histories_orig.csv"
LOADER = SOURCE_ROOT / "adr4ai_app/experiments/pattern_selection/prepare_data.py"


def render_outputs() -> dict[Path, str]:
    spec = importlib.util.spec_from_file_location("original_prepare_data", LOADER)
    if spec is None or spec.loader is None:
        raise ValueError(f"Cannot load original requirement validator: {LOADER}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    cases = module.load_requirement_cases(SOURCE)
    systems = {}
    for case in cases:
        story_id = case["user_story_id"]
        system_id = story_id.split("-", 1)[0]
        if system_id not in {"SYS01", "SYS02", "SYS03", "SYS04"}:
            raise ValueError(f"Unexpected system identifier: {system_id}")
        expected_system = f"System_{system_id[-2:]}"
        if case["system"] != expected_system:
            raise ValueError(f"System/story identifier mismatch: {story_id}")
        if story_id not in {f"{system_id}-US{number:02d}" for number in range(1, 4)}:
            raise ValueError(f"Unexpected story identifier: {story_id}")
        group = systems.setdefault(system_id, {"stories": 0, "criteria": 0})
        group["stories"] += 1
        group["criteria"] += len(case["acceptance_criteria"])
        for criterion in case["acceptance_criteria"]:
            if not criterion["acceptance_criterion_id"].startswith(story_id + "-AC"):
                raise ValueError(f"Criterion belongs to a different story: {criterion}")

    story_count = sum(group["stories"] for group in systems.values())
    criterion_count = sum(group["criteria"] for group in systems.values())
    if len(systems) != 4 or story_count != 12 or criterion_count != 35:
        raise ValueError("Unexpected sample totals")
    if any(group["stories"] != 3 for group in systems.values()):
        raise ValueError("Expected three stories for every system")

    macros = (
        "% !TeX root = ../main.tex\n"
        "% Generated by processing/scripts/prepare_dataset_summary.py.\n"
        f"\\newcommand{{\\StudySystemCount}}{{{len(systems)}}}\n"
        f"\\newcommand{{\\StudyStoryCount}}{{{story_count}}}\n"
        "\\newcommand{\\StudyStoriesPerSystem}{3}\n"
        f"\\newcommand{{\\StudyCriterionCount}}{{{criterion_count}}}\n"
    )
    rows = "\n".join(
        f"{system_id} & {group['stories']} & {group['criteria']} " + r"\\"
        for system_id, group in sorted(systems.items())
    )
    table = (
        "% !TeX root = ../main.tex\n"
        "% Generated by processing/scripts/prepare_dataset_summary.py.\n"
        "\\begin{table}[t]\n"
        "\\caption{The bounded industrial requirement sample.}\n"
        "\\label{tab:dataset-summary}\n"
        "\\centering\n"
        "\\begin{tabular}{lrr}\n"
        "\\hline\n"
        "\\textbf{System ID} & \\textbf{User stories} & \\textbf{Acceptance criteria} \\\\\n"
        "\\hline\n"
        + rows
        + "\n\\hline\n"
        "Total & \\StudyStoryCount{} & \\StudyCriterionCount{} \\\\\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\end{table}\n"
    )
    audit = {
        "task": "1.2",
        "source": SOURCE.relative_to(PROJECT).as_posix(),
        "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
        "validator": LOADER.relative_to(PROJECT).as_posix(),
        "validator_sha256": hashlib.sha256(LOADER.read_bytes()).hexdigest(),
        "system_count": len(systems),
        "story_count": story_count,
        "criterion_count": criterion_count,
        "systems": dict(sorted(systems.items())),
    }
    return {
        LATEX / "data/study-values.tex": macros,
        LATEX / "tables/dataset-summary.tex": table,
        PROJECT / "processing/outputs/dataset-summary-audit.json":
            json.dumps(audit, indent=2, sort_keys=True) + "\n",
    }


def main() -> int:
    if sys.argv[1:] not in ([], ["--check"]):
        raise ValueError("Usage: prepare_dataset_summary.py [--check]")
    outputs = render_outputs()
    if sys.argv[1:] == ["--check"]:
        for path, content in outputs.items():
            if path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Generated artifact is stale: {path}")
        print("PASS: dataset validation and all generated artifacts match")
    else:
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(PROJECT)}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, ImportError) as error:
        print(f"Dataset summary failed: {error}", file=sys.stderr)
        sys.exit(1)
