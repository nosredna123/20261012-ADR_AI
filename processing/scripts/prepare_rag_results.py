"""Recompute descriptive same-story final Top-5 overlap without model execution."""

import csv
import hashlib
import importlib.util
import json
from pathlib import Path
import sys

PROJECT = Path(__file__).resolve().parents[2]
SCRIPT = Path(__file__).with_name("prepare_study_values.py")
SPEC = importlib.util.spec_from_file_location("study_values", SCRIPT)
if SPEC is None or SPEC.loader is None:
    raise ImportError(f"Cannot load study-value validator: {SCRIPT}")
study = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(study)
AUDIT = PROJECT / "processing/outputs/rag-results-audit.json"
MACROS = PROJECT / "latex-code/data/rag-results-values.tex"
TABLE = PROJECT / "latex-code/tables/rag-comparison.tex"


def compare_sets(positives: dict[str, set[str]], rankings: dict[str, list[str]]) -> dict:
    if not positives or set(positives) != set(rankings):
        raise ValueError("Positive-set and ranking story coverage differ")
    stories = {}
    for uid, selected in sorted(positives.items()):
        top = rankings[uid]
        if len(top) != 5 or len(set(top)) != 5:
            raise ValueError(f"Expected five distinct final candidates: {uid}")
        for pid in selected | set(top):
            if not isinstance(pid, str) or pid not in {f"{n:03d}" for n in range(1, 71)}:
                raise ValueError(f"Unknown or noncanonical pattern ID: {uid}")
        matches = selected & set(top)
        stories[uid] = {
            "positive_count": len(selected), "overlap_count": len(matches),
            "outside_count": len(selected - set(top)),
            "matched_pattern_ids": sorted(matches),
            "final_top5_ids": top,
            "overlap_percent": f"{100 * len(matches) / len(selected):.2f}" if selected else None,
        }
    positive_count = sum(row["positive_count"] for row in stories.values())
    overlap_count = sum(row["overlap_count"] for row in stories.values())
    return {
        "stories": stories, "positive_count": positive_count,
        "overlap_count": overlap_count,
        "outside_count": positive_count - overlap_count,
        "overlap_story_count": sum(row["overlap_count"] > 0 for row in stories.values()),
        "pooled_overlap_percent": f"{100 * overlap_count / positive_count:.2f}"
        if positive_count else None,
    }


def audit_results() -> dict:
    central = study.audit_values()
    compiler = study.load_module(study.RESULTS / "compile_results.py")
    selected, summary, _ = compiler.compile_results()
    positives = {row["user_story_id"]: set() for row in summary}
    for row in selected:
        positives[row["user_story_id"]].add(row["pattern_id"])
    with (study.SOURCE / "experiments/rag/outputs/rag_baseline.csv").open(
        encoding="utf-8-sig", newline=""
    ) as stream:
        rankings = {row["user_story_id"]: row["top5_ids"].split(";")
                    for row in csv.DictReader(stream)}
    result = compare_sets(positives, rankings)
    for row in summary:
        observed = result["stories"][row["user_story_id"]]
        if (observed["positive_count"] != row["applicable_count"]
                or observed["overlap_count"] != row["rag_top5_overlap_count"]):
            raise ValueError("Direct set intersection differs from frozen summary")
    for key, macro in (
        ("positive_count", "StudyApplicableCount"), ("overlap_count", "StudyRagOverlapCount"),
        ("outside_count", "StudyRagOutsideCount"),
        ("overlap_story_count", "StudyRagOverlapStoryCount"),
    ):
        if result[key] != central["values"][macro]["value"]:
            raise ValueError(f"RQ2 and central values disagree: {key}")
    return {
        "task": "2.3", **result,
        "inputs": central["inputs"] + [{
            "path": Path(__file__).resolve().relative_to(PROJECT).as_posix(),
            "sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        }],
        "definition": "Same-story intersection of LLM-positive pattern IDs and frozen final Top-5 IDs.",
        "percentage": "100 * intersection / LLM-positive count; pooled ratio, not mean story percentage; two-decimal display.",
        "zero_positive": "Retain zero counts; percentage undefined, displayed as --, not zero.",
        "scope": "Candidate overlap only; no precision, recall, accuracy or superiority.",
    }


def render_outputs(audit: dict) -> dict[Path, str]:
    if audit["pooled_overlap_percent"] is None:
        raise ValueError("Empirical pooled overlap requires at least one positive pair")
    lines = [
        "% !TeX root = ../main.tex",
        "% Generated by processing/scripts/prepare_rag_results.py.",
        r"\begin{table}[t]",
        r"\caption{RQ2 final Top-5 membership among LLM-positive pairs. Percentage denominator: positive pairs in the row; -- denotes an undefined percentage for a zero-positive story.}",
        r"\label{tab:rag-comparison}", r"\centering", r"\small",
        r"\begin{tabular}{lrrrr}", r"\hline",
        r"Story & Positive & In & Out & \% in \\", r"\hline",
    ]
    for uid, row in audit["stories"].items():
        percent = row["overlap_percent"] if row["overlap_percent"] is not None else "--"
        lines.append(f"{uid} & {row['positive_count']} & {row['overlap_count']}"
                     f" & {row['outside_count']} & {percent} " + r"\\")
    lines.extend([
        r"\hline",
        r"Pooled & \StudyApplicableCount{} & \StudyRagOverlapCount{} & \StudyRagOutsideCount{} & \RqTwoOverlapPercent{} \\",
        r"\hline", r"\end{tabular}", r"\end{table}",
    ])
    return {
        AUDIT: json.dumps(audit, indent=2, sort_keys=True) + "\n",
        MACROS: (
            "% !TeX root = ../main.tex\n"
            "% Generated by processing/scripts/prepare_rag_results.py.\n"
            f"\\newcommand{{\\RqTwoOverlapPercent}}{{{audit['pooled_overlap_percent']}}}\n"
        ),
        TABLE: "\n".join(lines) + "\n",
    }


def main() -> int:
    if sys.argv[1:] not in ([], ["--check"]):
        raise ValueError("Usage: prepare_rag_results.py [--check]")
    outputs = render_outputs(audit_results())
    for path, content in outputs.items():
        if sys.argv[1:] == ["--check"]:
            if path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Stale RQ2 artifact: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(PROJECT)}")
    print("PASS: RQ2 same-story final Top-5 overlap reconciled")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, ImportError, KeyError) as error:
        print(f"RQ2 preparation failed: {error}", file=sys.stderr)
        sys.exit(1)
