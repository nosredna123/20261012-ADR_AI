"""Validate the pre-inspection protocol and render its output inventory; no responses."""

import hashlib
import json
from pathlib import Path
import sys

PROJECT = Path(__file__).resolve().parents[2]
PROTOCOL = PROJECT / "processing/protocols/expert-analysis.json"
PREPARATION = PROJECT / "processing/outputs/expert-preparation-audit.json"
AUDIT = PROJECT / "processing/outputs/expert-analysis-plan-audit.json"
TABLE = PROJECT / "latex-code/tables/expert-analysis-outputs.tex"
OUTPUT_IDS = {"sample", "items", "cases", "hierarchy", "figure", "agreement",
              "sensitivity", "themes"}


def validate_protocol(protocol: dict, preparation: dict) -> None:
    if (protocol["task"] != "1.8"
            or protocol["timing"]["response_values_inspected_for_this_protocol"] is not False
            or protocol["timing"]["preregistered_before_collection"] is not False
            or protocol["interpretation"]["mode"] != "exploratory_descriptive"):
        raise ValueError("Protocol timing or exploratory scope differs from approved decisions")
    if protocol["status"] not in {"pending_human_review", "approved"}:
        raise ValueError("Unknown protocol review status")
    if protocol["rating_values"] != [1, 2, 3, 4, 5]:
        raise ValueError("Expected the five ordinal rating categories")
    expected_items = [item["id"] for item in preparation["questionnaire"]["evaluation_questions"]]
    if protocol["items"] != expected_items or expected_items != ["Q1", "Q2", "Q3", "Q4", "Q5"]:
        raise ValueError("Analysis items differ from prepared questionnaire")
    if any(protocol["ordinal_summary"][key] is not False
           for key in ("means", "composite_scores", "significance_tests")):
        raise ValueError("Unapproved numeric/composite/inferential analysis")
    if any(protocol["interpretation"][key] is not None
           for key in ("binary_validated_threshold", "favorable_rating_cutoff")):
        raise ValueError("Unapproved expert-validation cutoff")
    if (protocol["cell_rules"]["no_imputation"] is not True
            or protocol["inclusion"]["exclude_by_rating_direction"] is not False
            or protocol["inclusion"]["minimum_experience_years"] is not None
            or protocol["inclusion"]["minimum_system_knowledge_score"] is not None):
        raise ValueError("Eligibility or missing-data rules differ from approved decisions")
    outputs = protocol["outputs"]
    if len(outputs) != len(OUTPUT_IDS) or {item["id"] for item in outputs} != OUTPUT_IDS:
        raise ValueError("Planned output inventory is incomplete or duplicated")
    targets = set()
    for item in outputs:
        if any(not isinstance(item.get(field), str) or not item[field].strip()
               for field in ("id", "target", "source", "computation", "display")):
            raise ValueError("Every output needs a source, computation and display rule")
        target = Path(item["target"])
        if (target.is_absolute() or ".." in target.parts or item["target"] in targets
                or target.parts[:2] not in (("latex-code", "tables"),
                                           ("latex-code", "figures"),
                                           ("processing", "outputs"))):
            raise ValueError(f"Invalid or duplicate planned output path: {target}")
        targets.add(item["target"])


def tex_text(text: str) -> str:
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(character, character) for character in text)


def render_outputs() -> dict[Path, str]:
    protocol = json.loads(PROTOCOL.read_text(encoding="utf-8"))
    preparation = json.loads(PREPARATION.read_text(encoding="utf-8"))
    validate_protocol(protocol, preparation)
    rows = "\n".join(
        f"{tex_text(item['id'].title())} & "
        f"{tex_text(item['source'])} {tex_text(item['computation'])} " + r"\\"
        for item in protocol["outputs"]
    )
    table = (
        "% !TeX root = ../main.tex\n"
        "% Generated by processing/scripts/prepare_expert_analysis_plan.py.\n"
        "\\begin{table*}[t]\n"
        "\\caption{Predeclared expert-analysis output inventory. These are planned "
        "outputs, not observations; aggregate publication requires disclosure review.}\n"
        "\\label{tab:expert-analysis-outputs}\n"
        "\\centering\\small\n"
        "\\begin{tabular}{lp{0.86\\textwidth}}\n\\hline\n"
        "\\textbf{Output} & \\textbf{Source and computation} \\\\\n\\hline\n"
        + rows + "\n\\hline\n\\end{tabular}\n\\end{table*}\n"
    )
    audit = {
        "task": "1.8", "protocol_id": protocol["protocol_id"],
        "protocol_sha256": hashlib.sha256(PROTOCOL.read_bytes()).hexdigest(),
        "prepared_instrument_audit_sha256": hashlib.sha256(PREPARATION.read_bytes()).hexdigest(),
        "review_status": protocol["status"],
        "planned_output_ids": [item["id"] for item in protocol["outputs"]],
        "response_data_read": False,
        "validation_scope": "Protocol consistency and inventory rendering, not execution of response statistics.",
    }
    return {TABLE: table, AUDIT: json.dumps(audit, indent=2, sort_keys=True) + "\n"}


def main() -> int:
    if sys.argv[1:] not in ([], ["--check"]):
        raise ValueError("Usage: prepare_expert_analysis_plan.py [--check]")
    outputs = render_outputs()
    for path, content in outputs.items():
        if sys.argv[1:] == ["--check"]:
            if path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Stale expert-analysis plan artifact: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(PROJECT)}")
    print("PASS: pre-inspection analysis protocol and output inventory")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Analysis-plan verification failed: {error}", file=sys.stderr)
        sys.exit(1)
